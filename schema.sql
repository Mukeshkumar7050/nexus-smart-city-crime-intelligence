CREATE TABLE IF NOT EXISTS users (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(50) NOT NULL UNIQUE,
  password_hash VARCHAR(100) NOT NULL,
  role VARCHAR(30) NOT NULL
);
CREATE TABLE IF NOT EXISTS incidents (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  type VARCHAR(20) NOT NULL,
  location VARCHAR(120) NOT NULL,
  zone VARCHAR(50) NOT NULL,
  description VARCHAR(500),
  status VARCHAR(20) NOT NULL DEFAULT 'Active',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS units (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  code VARCHAR(10) NOT NULL UNIQUE,
  officer VARCHAR(60) NOT NULL,
  zone VARCHAR(50) NOT NULL,
  status VARCHAR(20) NOT NULL
);
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS lat DOUBLE;
ALTER TABLE incidents ADD COLUMN IF NOT EXISTS lng DOUBLE;
ALTER TABLE units ADD COLUMN IF NOT EXISTS lat DOUBLE;
ALTER TABLE units ADD COLUMN IF NOT EXISTS lng DOUBLE;
CREATE TABLE IF NOT EXISTS audit_log (
  id BIGINT AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(50),
  action VARCHAR(30) NOT NULL,
  detail VARCHAR(200),
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_inc_created ON incidents(created_at);
